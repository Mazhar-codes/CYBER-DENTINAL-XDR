#!/usr/bin/env python3
"""
check_payload.py — Telemetry payload diagnostic / validation script
Cyber Sentinel XDR — Endpoint Agent

PURPOSE
-------
Runs on the endpoint machine and verifies that every telemetry field the
backend expects is present and correctly typed in what the agent actually
sends.  Prints a clear PASS / FAIL / WARN report per field.

USAGE
-----
    python check_payload.py
    python check_payload.py --url http://192.168.1.100:8000 --key YOUR_API_KEY
    python check_payload.py --no-live-post

ENVIRONMENT VARIABLES (used when no CLI flags supplied)
-------------------------------------------------------
    XDR_BACKEND_URL   Backend base URL  (default: http://localhost:8000)
    XDR_API_KEY       API key           (default: changeme-dev-key)
"""

# ---------------------------------------------------------------------------
# CANONICAL FIELD LISTS
# Derived directly from the backend Pydantic models in backend.py:
#
#   class EndpointIdentity(BaseModel):   line 925
#   class EndpointTelemetry(BaseModel):  line 935
#
# Format: { "field_name": expected_python_type }
# Types map to what the backend model declares OR what the agent sends after
# the collector returns and the payload dict is assembled.
# ---------------------------------------------------------------------------

# EndpointIdentity — nested under payload["endpoint"]
CANONICAL_ENDPOINT: dict[str, type] = {
    "endpoint_id":      str,
    "hostname":         str,
    "ip_address":       str,
    "os":               str,
    "os_version":       str,
    "username":         str,
    "agent_version":    str,
    # network_interface is generated by identity.py (not in EndpointIdentity model
    # but present in the agent payload — flagged as INFO rather than FAIL)
}

# EndpointTelemetry top-level fields (excluding "endpoint" which is checked separately)
CANONICAL_TELEMETRY_TOP: dict[str, type] = {
    "timestamp":            str,    # ISO 8601 string from agent; backend auto-fills if absent
    "network":              dict,
    "system":               dict,
    "user":                 dict,
    "malware":              dict,
    "winlogbeat_events":    dict,   # agent sends {} — backend coerces [] to {}
}

# payload["network"] — from network_collector.collect_network()
# Backend reads: connections, bytes_sent, bytes_recv, suspicious_ports
# Also stored: packets_sent, packets_recv
CANONICAL_NETWORK: dict[str, type] = {
    "connections":      list,   # list of dicts; max 50
    "bytes_sent":       int,
    "bytes_recv":       int,
    "packets_sent":     int,
    "packets_recv":     int,
    "suspicious_ports": list,   # list of int
}

# Each item inside payload["network"]["connections"]
CANONICAL_NETWORK_CONN: dict[str, type] = {
    "laddr":    str,
    "raddr":    str,
    "status":   str,
    "pid":      (int, type(None)),  # pid can be None on some platforms
}

# payload["system"] — from system_collector.collect_system()
# Backend reads: cpu_percent, memory_percent, processes
CANONICAL_SYSTEM: dict[str, type] = {
    "cpu_percent":      float,
    "memory_percent":   float,
    "memory_used_mb":   float,
    "disk_percent":     float,
    "process_count":    int,
    "processes":        list,   # top 10 by CPU; list of dicts
}

# Each item inside payload["system"]["processes"]
CANONICAL_SYSTEM_PROC: dict[str, type] = {
    "pid":          (int, type(None)),
    "name":         str,
    "cpu_percent":  float,
    "memory_mb":    float,
}

# payload["user"] — from user_collector.collect_user()
# Backend UserBehaviorAgent.score_session_telemetry() reads:
#   current_user, sessions, session_count
CANONICAL_USER: dict[str, type] = {
    "current_user":     str,
    "sessions":         list,   # list of dicts
    "session_count":    int,
}

# Each item inside payload["user"]["sessions"]
CANONICAL_USER_SESSION: dict[str, type] = {
    "user":     str,
    "terminal": str,
    "host":     str,
    "started":  str,    # ISO-like string from strftime in user_collector
}

# payload["malware"] — from malware_collector.collect_malware()
# Backend MalwareAnalysisAgent.assess_process_metadata() reads:
#   suspicious, processes (full list), scanned_count
CANONICAL_MALWARE: dict[str, type] = {
    "scanned_count":    int,
    "suspicious":       list,   # list of dicts
    "processes":        list,   # full process list (name + pid)
}

# Each item inside payload["malware"]["suspicious"]
CANONICAL_MALWARE_SUSP: dict[str, type] = {
    "pid":      int,
    "name":     str,
    "path":     str,
    "reason":   str,
}

