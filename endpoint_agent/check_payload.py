async def main() -> int:
    parser = argparse.ArgumentParser(
        description=(
            "Cyber Sentinel XDR — Telemetry payload diagnostic tool.\n"
            "Calls each collector, assembles the exact payload the agent sends,\n"
            "and verifies every field against the backend Pydantic model spec."
        ),
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument(
        "--url",
        default=os.environ.get("XDR_BACKEND_URL", "http://localhost:8000"),
        metavar="URL",
        help="XDR backend base URL  (env: XDR_BACKEND_URL)",
    )
    parser.add_argument(
        "--key",
        default=os.environ.get("XDR_API_KEY", "changeme-dev-key"),
        metavar="KEY",
        help="API key for X-API-Key header  (env: XDR_API_KEY)",
    )
    parser.add_argument(
        "--no-live-post",
        action="store_true",
        default=False,
        help="Skip the live POST test (schema check only)",
    )
    args = parser.parse_args()

    print(_c(_BOLD, "\nCyber Sentinel XDR — Telemetry Payload Diagnostic"))
    print("=" * 60)
    print(f"  Run time : {datetime.now(timezone.utc).isoformat()}")
    print(f"  Backend  : {args.url}")
    print(f"  Platform : {sys.platform}")
    print("=" * 60)

    # ------------------------------------------------------------------
    # 1. Import collectors and identity
    # ------------------------------------------------------------------
    print("\nLoading collectors...", end=" ", flush=True)
    try:
        from collectors import collect_network, collect_system, collect_user, collect_malware
        from identity import get_identity
        print(_c(_GREEN, "OK"))
    except ImportError as exc:
        print(_c(_RED, f"FAILED — {exc}"))
        print(
            "\nEnsure you are running from inside endpoint_agent/ or that\n"
            "D:\\Cyber Sentinal\\endpoint_agent is on PYTHONPATH.\n"
        )
        return 1

    # ------------------------------------------------------------------
    # 2. Collect live telemetry
    # ------------------------------------------------------------------
    print("Collecting telemetry from collectors...", end=" ", flush=True)
    try:
        network, system, user, malware = await asyncio.gather(
            collect_network(),
            collect_system(),
            collect_user(),
            collect_malware(),
        )
        print(_c(_GREEN, "OK"))
    except Exception as exc:
        print(_c(_RED, f"FAILED — {exc}"))
        return 1

    print("Loading endpoint identity...", end=" ", flush=True)
    try:
        identity = get_identity()
        print(_c(_GREEN, "OK"))
    except Exception as exc:
        print(_c(_RED, f"FAILED — {exc}"))
        return 1

    # ------------------------------------------------------------------
    # 3. Assemble payload exactly as agent.py does
    # ------------------------------------------------------------------
    payload: dict = {
        "endpoint":           identity,
        "timestamp":          datetime.now(timezone.utc).isoformat(),
        "network":            network,
        "system":             system,
        "user":               user,
        "malware":            malware,
        "winlogbeat_events":  {},
    }

    # ------------------------------------------------------------------
    # 4. Validate each section
    # ------------------------------------------------------------------
    sections = [
        validate_telemetry_top(payload),
        validate_endpoint(identity),
        validate_network(network),
        validate_system(system),
        validate_user(user),
        validate_malware(malware),
    ]

    for sec in sections:
        sec.print()

    # ------------------------------------------------------------------
    # 5. Overall summary
    # ------------------------------------------------------------------
    total_passed = sum(s.passed for s in sections)
    total_failed = sum(s.failed for s in sections)
    total_warned = sum(s.warned for s in sections)
    total_fields = sum(s.total  for s in sections)

    print("\n" + "=" * 60)
    print(_c(_BOLD, "OVERALL SUMMARY"))
    print("=" * 60)

    ok_colour  = _GREEN if total_failed == 0 else _RED
    print(_c(ok_colour, f"  {total_passed}/{total_fields} fields OK"))
    if total_failed:
        print(_c(_RED,    f"  {total_failed} FAILED  — these fields are missing or wrong type"))
    if total_warned:
        print(_c(_YELLOW, f"  {total_warned} WARNINGS — type mismatch or extra fields; "
                          "backend may still accept them via coercion"))

    if total_failed == 0 and total_warned == 0:
        print(_c(_GREEN, "\n  All canonical fields present and correctly typed."))
        print(  "  The payload should be accepted by the backend without errors.")
    elif total_failed == 0:
        print(_c(_YELLOW, "\n  No hard failures; warnings may be harmless (backend coerces many types)."))
    else:
        print(_c(_RED, "\n  Fix FAILED fields before deploying — they will cause 422 errors."))

    # ------------------------------------------------------------------
    # 6. Pretty-print raw payload (optional, for manual inspection)
    # ------------------------------------------------------------------
    print("\n" + "=" * 60)
    print(_c(_BOLD, "RAW PAYLOAD SNAPSHOT"))
    print("=" * 60)
    # Truncate long lists to keep output readable
    def _trim(obj: Any, list_max: int = 3) -> Any:
        if isinstance(obj, list):
            trimmed = [_trim(i, list_max) for i in obj[:list_max]]
            if len(obj) > list_max:
                trimmed.append(f"... ({len(obj) - list_max} more items)")
            return trimmed
        if isinstance(obj, dict):
            return {k: _trim(v, list_max) for k, v in obj.items()}
        return obj

    snapshot = _trim(payload)
    print(json.dumps(snapshot, indent=2, default=str))

    # ------------------------------------------------------------------
    # 7. Live POST test
    # ------------------------------------------------------------------
    if not args.no_live_post:
        await _live_post_test(payload, args.url, args.key)
    else:
        print(_c(_CYAN, "\n  [SKIP] Live POST test disabled via --no-live-post"))

    print()
    return 0 if total_failed == 0 else 1


if __name__ == "__main__":
    sys.exit(asyncio.run(main()))
